POPUP_KEYWORDS = [

    "팝업",
    "팝업스토어",
    "전시",
    "브랜드",
    "굿즈",
    "캐릭터",

    "성수",
    "홍대",
    "강남",
    "잠실",
    "명동",

    "더현대",
    "현대백화점",
    "롯데월드몰",
    "아이파크몰",

    "예약",
    "행사",
    "스토어"

]


def is_popup_question(question: str):

    """
    사용자 질문에 팝업 관련 키워드가 포함되어 있는지 확인한다.
    """

    return any(keyword in question for keyword in POPUP_KEYWORDS)