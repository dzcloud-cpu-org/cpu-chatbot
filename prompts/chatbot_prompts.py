# ==========================================================
# User Prompt Builder
# ==========================================================

def build_search_condition_user_prompt(
    user_question: str,
    today_str: str | None = None,
) -> str:
    """
    [1단계] 검색 조건 생성용 User Prompt

    SEARCH_CONDITION_PROMPT(system)가
    출력 형식과 규칙을 모두 정의하므로

    User Prompt에는 사용자 질문과(선택적으로) 오늘 날짜만 전달한다.

    Gemini는 학습 시점 이후의 "현재 날짜"를 알 수 없기 때문에,
    "오늘"/"이번주" 같은 표현을 판단할 때 참고할 수 있도록
    서버에서 계산한 오늘 날짜(today_str)를 함께 전달한다.

    다만 실제 날짜 범위(예: 이번주 월~일)의 계산과
    MongoDB 쿼리 변환은 어디까지나 서버(mongo_service.py)에서 수행하며,
    Gemini는 date_filter를 "today" / "this_week" / null 중 하나로
    분류하는 역할만 담당한다.
    """

    today_line = f"오늘 날짜: {today_str}\n\n" if today_str else ""

    return f"""
{today_line}사용자 질문:

{user_question}

위 질문을 분석하여
규칙에 정의된 JSON 형식으로만 응답하세요.
"""


def build_chatbot_answer_user_prompt(
    user_question: str,
    search_condition: dict,
    popup_info: str,
) -> str:
    """
    [2단계] 최종 답변 생성용 User Prompt
    """

    intent = search_condition.get("intent", "recommend")

    return f"""
사용자 질문

{user_question}

질문 의도(intent)

{intent}

MongoDB 검색 결과

{popup_info}

반드시 위 검색 결과만 이용하여 답변하세요.

검색 결과에 source_url이 있으면
반드시 상세 페이지(URL)도 함께 안내하세요.

없는 정보는 절대 생성하지 마세요.
"""