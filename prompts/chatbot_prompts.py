# ==========================================================
# User Prompt 빌더
#
# System Prompt(역할/규칙)와 User Prompt(실제 데이터)를 분리해서
# gemini_service.generate_structured_response / generate_chat_response 에
# 각각 system_prompt / user_prompt 인자로 전달한다.
#
# System Prompt는 "고정된 지시사항"이고,
# User Prompt는 "요청마다 달라지는 실제 입력값"이라는 역할 분리를 유지한다.
# ==========================================================


def build_search_condition_user_prompt(user_question: str) -> str:
    """
    [1단계] 검색 조건 생성용 User Prompt

    SEARCH_CONDITION_PROMPT(system)가 이미 출력 형식/규칙을 모두 규정하므로
    User Prompt에는 사용자의 원본 질문만 그대로 전달한다.
    """

    return f"""
        사용자 질문:

        {user_question}

        위 질문을 분석하여 규칙에 정의된 JSON 형식으로만 응답하세요.
        """


def build_chatbot_answer_user_prompt(
    user_question: str,
    search_condition: dict,
    popup_info: str,
) -> str:
    """
    [2단계] 최종 답변 생성용 User Prompt

    - user_question   : 사용자가 입력한 원본 질문
    - search_condition: 1단계 Gemini가 생성한 검색 조건(JSON) - 질문 의도(intent) 파악용
    - popup_info      : MongoDB에서 조회된 팝업 정보를 정제한 텍스트

    intent를 함께 전달하는 이유:
    CHATBOT_RESPONSE_PROMPT 규칙 4번("질문 의도에 맞는 정보만 답변")을
    Gemini가 더 정확히 지키도록 돕기 위함이다.
    (예: intent="operation"이면 운영기간/시간 위주로만 답변하도록 유도)
    """

    intent = search_condition.get("intent", "recommend")

    return f"""
        사용자 질문:

        {user_question}

        질문 의도(intent):

        {intent}

        검색된 팝업스토어 정보:

        {popup_info}

        위 데이터만 참고하여 사용자 질문에 답변해줘.
        """
